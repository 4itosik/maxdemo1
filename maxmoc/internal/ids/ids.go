// Package ids — генерация идентификаторов в форматах, близких к Max.
//
// Форматы подобраны по наблюдениям из документации: контракт объявляет их
// строками и числами без дополнительных ограничений, поэтому расхождение с
// продом не ломает интеграцию, но правдоподобие облегчает отладку.
package ids

import (
	"crypto/rand"
	"encoding/base64"
	"encoding/binary"
	"encoding/hex"
	"fmt"
)

func randUint64() uint64 {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic("ids: источник случайности недоступен: " + err.Error())
	}
	return binary.BigEndian.Uint64(b[:])
}

// maxSafeID — верхняя граница генерируемых идентификаторов.
//
// Контракт объявляет chat_id и user_id как int64, но JSON-числа в JavaScript
// — это float64, и целые больше 2^53−1 там теряют точность. Через JS проходят
// и веб-UI мока, и клиенты КЦ на Node; идентификатор, который «поедет» при
// разборе ответа, сделал бы мок источником неверных отчётов об ошибках.
// Поэтому генерируем в диапазоне 2^52 — с запасом внутри безопасной зоны и
// по порядку близко к реальным идентификаторам Max.
const maxSafeID = int64(1) << 52

// randSafeID возвращает положительный идентификатор, безопасный для JSON.
func randSafeID() int64 {
	n := int64(randUint64()%uint64(maxSafeID-1)) + 1
	return n
}

// NewChatID — идентификатор диалога.
func NewChatID() int64 { return randSafeID() }

// NewUserID — идентификатор пользователя или бота.
func NewUserID() int64 { return randSafeID() }

// seqCounterBits — ширина счётчика в младших битах seq.
//
// Разрядность взята из образца с прода: там seq = 117052520019991875 при
// timestamp сообщения 1786079712219, и seq >> 16 даёт ровно timestamp.
const (
	seqCounterBits = 16
	seqCounterMask = 1<<seqCounterBits - 1
)

// Seq — порядковый номер сообщения в чате в формате живого Max: время
// создания в старших битах, счётчик внутри миллисекунды — в младших.
//
// Формат нарочно воспроизведён точно, хотя контракт объявляет seq просто
// int64. Значение выходит за 2^53, то есть теряет точность при разборе в
// JavaScript — и это то расхождение, которое мок обязан показывать, а не
// скрывать: небольшой счётчик (1, 2, 3…) в моке молча пропустил бы клиента,
// который на проде получит искажённый номер. Идентификаторы чатов и
// пользователей, наоборот, держатся внутри безопасной зоны (см. maxSafeID) —
// там живой Max выдаёт значения на порядки меньше.
//
// Счётчик берётся случайным: в единственном образце с прода он равен 7491, и
// вывести из одного значения его происхождение нельзя. Ноль там был бы хуже
// произвольного числа — `время << 16` укладывается в 41 значащий бит и
// проходит через float64 без потерь, то есть ровно та поломка, которую мок
// должен показывать, снова оказалась бы скрыта.
//
// prevSeq — наибольший номер, уже выданный в этом чате. Если полученное
// значение его не превысило (второе сообщение в ту же миллисекунду, неудачный
// счётчик или ушедшие назад часы), номер берётся на единицу больше
// предыдущего: строгий рост нужен и сортировке ленты, и ограничению
// UNIQUE (chat_id, seq).
func Seq(createdAtMS, prevSeq int64) int64 {
	s := createdAtMS<<seqCounterBits | int64(randUint64()&seqCounterMask)
	if s <= prevSeq {
		s = prevSeq + 1
	}
	return s
}

// Mid — идентификатор сообщения: chat_id и порядковый номер, упакованные в
// hex по 16 символов каждый, как на проде (`mid.000000001a5b94f2019fdaa593db1d43`
// — это chat_id 442209522 и seq 117052520019991875). Детерминирован, поэтому
// по mid всегда видно, к какому чату он относится.
func Mid(chatID, seq int64) string {
	return fmt.Sprintf("mid.%016x%016x", uint64(chatID), uint64(seq))
}

// NewToken — непрозрачный токен вида `<prefix>.<32 hex>`.
func NewToken(prefix string) string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic("ids: источник случайности недоступен: " + err.Error())
	}
	return prefix + "." + hex.EncodeToString(b[:])
}

// NewBotToken — access_token бота (выдаётся при регистрации в моке).
func NewBotToken() string { return NewToken("bot") }

// callbackIDBytes — длина случайной части callback_id.
//
// 87 байт в base64url дают ровно 116 символов без выравнивания — столько же,
// сколько в образце с прода, и он декодируется ровно в 87 байт.
const callbackIDBytes = 87

// NewCallbackID — идентификатор нажатия кнопки.
//
// Формат повторяет живой Max: base64url без префикса, 116 символов. Прежний
// `cb.<32 hex>` был втрое короче, а длина здесь не косметика — клиент, у
// которого под callback_id заведена короткая колонка или буфер, на моке
// проходил бы, а на проде обрезал идентификатор и терял ответ на нажатие.
// Алфавит base64url выбран не случайно: идентификатор уезжает обратно
// query-параметром POST /answers, и экранировать его не приходится.
func NewCallbackID() string {
	var b [callbackIDBytes]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic("ids: источник случайности недоступен: " + err.Error())
	}
	return base64.RawURLEncoding.EncodeToString(b[:])
}

// NewUploadToken — токен загрузки/вложения.
func NewUploadToken() string { return NewToken("att") }
